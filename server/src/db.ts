import "dotenv/config";
import pg from "pg";

const { Pool } = pg;

export const pool = new Pool({
  host: process.env.PGHOST ?? "127.0.0.1",
  port: Number(process.env.PGPORT ?? 5432),
  database: process.env.PGDATABASE ?? "gymadmin",
  user: process.env.PGUSER ?? "gymadmin_app",
  password: process.env.PGPASSWORD,
  ssl: process.env.PGSSLMODE === "require" ? { rejectUnauthorized: false } : false,
  max: 10,
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 5_000
});

export async function initDb() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS members (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      first_name TEXT NOT NULL,
      last_name TEXT NOT NULL,
      phone TEXT NOT NULL DEFAULT '',
      email TEXT NOT NULL DEFAULT '',
      joined_on DATE NOT NULL DEFAULT CURRENT_DATE,
      status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
      gender TEXT NOT NULL DEFAULT 'male' CHECK (gender IN ('male','female')),
      price_cents INTEGER NOT NULL DEFAULT 0 CHECK (price_cents >= 0),
      payment_method TEXT NOT NULL DEFAULT 'cash' CHECK (payment_method IN ('cash','transfer')),
      notes TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE IF NOT EXISTS plans (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      duration_days INTEGER NOT NULL CHECK (duration_days > 0),
      price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
      active BOOLEAN NOT NULL DEFAULT TRUE
    );

    CREATE TABLE IF NOT EXISTS memberships (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      member_id BIGINT NOT NULL REFERENCES members(id),
      plan_id BIGINT NOT NULL REFERENCES plans(id),
      start_date DATE NOT NULL,
      end_date DATE NOT NULL,
      price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
      status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','expired','cancelled')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE IF NOT EXISTS payments (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      member_id BIGINT NOT NULL REFERENCES members(id),
      membership_id BIGINT REFERENCES memberships(id),
      amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
      payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
      method TEXT NOT NULL CHECK (method IN ('cash','transfer')),
      reference TEXT NOT NULL DEFAULT '',
      notes TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE TABLE IF NOT EXISTS attendance (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      member_id BIGINT NOT NULL REFERENCES members(id),
      checkin_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE INDEX IF NOT EXISTS idx_members_last_first ON members(last_name, first_name);
    CREATE INDEX IF NOT EXISTS idx_payments_date ON payments(payment_date DESC);
    CREATE INDEX IF NOT EXISTS idx_memberships_end_date ON memberships(end_date);
    CREATE INDEX IF NOT EXISTS idx_attendance_checkin ON attendance(checkin_at DESC);

    CREATE TABLE IF NOT EXISTS membership_companions (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      membership_id BIGINT NOT NULL REFERENCES memberships(id) ON DELETE CASCADE,
      companion_member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (membership_id, companion_member_id)
    );

    CREATE INDEX IF NOT EXISTS idx_membership_companions_ms ON membership_companions(membership_id);
  `);

  await pool.query(`
    INSERT INTO plans (name, duration_days, price_cents)
    VALUES ('Membresía mensual', 30, 0)
    ON CONFLICT (name) DO NOTHING
  `);

  await pool.query(`
    ALTER TABLE members
    ADD COLUMN IF NOT EXISTS gender TEXT NOT NULL DEFAULT 'male'
  `);

  await pool.query(`
    ALTER TABLE members
    ADD COLUMN IF NOT EXISTS price_cents INTEGER NOT NULL DEFAULT 0
  `);

  await pool.query(`
    ALTER TABLE members
    ADD COLUMN IF NOT EXISTS payment_method TEXT NOT NULL DEFAULT 'cash'
  `);

  await pool.query(`
    ALTER TABLE memberships
    ADD COLUMN IF NOT EXISTS payment_method TEXT CHECK (payment_method IN ('cash','transfer'))
  `);

  await pool.query(`
    UPDATE memberships ms
    SET payment_method = p.method
    FROM payments p
    WHERE p.membership_id = ms.id AND ms.payment_method IS NULL
  `);

  await pool.query(`
    UPDATE payments p
    SET membership_id = ms.id
    FROM memberships ms
    WHERE p.membership_id IS NULL
      AND p.member_id = ms.member_id
      AND p.payment_date = ms.start_date
      AND p.notes = 'Membresía mensual'
      AND NOT EXISTS (SELECT 1 FROM payments p2 WHERE p2.membership_id = ms.id)
  `);

  await pool.query(`
    UPDATE memberships ms
    SET payment_method = p.method
    FROM payments p
    WHERE p.membership_id = ms.id AND ms.payment_method IS NULL
  `);

  await pool.query(`
  INSERT INTO payments (member_id, membership_id, amount_cents, payment_date, method, notes)
  SELECT
    ms.member_id,
    ms.id,
    GREATEST(ms.price_cents, 1),
    ms.start_date,
    COALESCE(ms.payment_method, 'cash'),
    'Membresía mensual'
  FROM memberships ms
  WHERE ms.price_cents >= 0
    AND NOT EXISTS (SELECT 1 FROM payments p WHERE p.membership_id = ms.id)
    AND ms.price_cents > 0
  `);

  await pool.query(`
    UPDATE memberships ms
    SET payment_method = COALESCE(ms.payment_method, p.method, 'cash')
    FROM payments p
    WHERE p.membership_id = ms.id AND ms.payment_method IS NULL
  `);

  await pool.query(`
    UPDATE memberships SET payment_method = 'cash' WHERE payment_method IS NULL
  `);

  await pool.query(`
    ALTER TABLE attendance
    ADD COLUMN IF NOT EXISTS visit_date DATE
  `);

  await pool.query(`
    UPDATE attendance
    SET visit_date = checkin_at::date
    WHERE visit_date IS NULL
  `);

  await pool.query(`
    CREATE UNIQUE INDEX IF NOT EXISTS idx_attendance_member_visit_date
    ON attendance (member_id, visit_date)
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS visit_exercises (
      member_id BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
      visit_date DATE NOT NULL,
      exercise_key TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      PRIMARY KEY (member_id, visit_date, exercise_key)
    )
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_visit_exercises_date
    ON visit_exercises (visit_date DESC)
  `);

  await pool.query(`
    DO $$ BEGIN
      ALTER TABLE visit_exercises
        ADD CONSTRAINT visit_exercises_attendance_fkey
        FOREIGN KEY (member_id, visit_date)
        REFERENCES attendance (member_id, visit_date)
        ON DELETE CASCADE;
    EXCEPTION WHEN duplicate_object THEN NULL;
    END $$
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS products (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      category TEXT NOT NULL DEFAULT 'otros'
        CHECK (category IN ('bebidas','suplementos','otros')),
      price_cents INTEGER NOT NULL CHECK (price_cents >= 0),
      active BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (name)
    );

    CREATE TABLE IF NOT EXISTS product_sales (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      product_id BIGINT NOT NULL REFERENCES products(id),
      quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0 AND quantity <= 999),
      unit_price_cents INTEGER NOT NULL CHECK (unit_price_cents >= 0),
      amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
      sale_date DATE NOT NULL DEFAULT CURRENT_DATE,
      method TEXT NOT NULL CHECK (method IN ('cash','transfer')),
      member_id BIGINT REFERENCES members(id) ON DELETE SET NULL,
      notes TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );

    CREATE INDEX IF NOT EXISTS idx_product_sales_date ON product_sales (sale_date DESC);
    CREATE INDEX IF NOT EXISTS idx_product_sales_product ON product_sales (product_id);
  `);

  await pool.query(`
    INSERT INTO products (name, category, price_cents, active)
    VALUES
      ('Agua', 'bebidas', 0, false),
      ('Bebida energética', 'bebidas', 0, false),
      ('Proteína en polvo', 'suplementos', 0, false)
    ON CONFLICT (name) DO NOTHING
  `);

  await pool.query(`
    ALTER TABLE products ALTER COLUMN active SET DEFAULT false
  `);

  await pool.query(`
    ALTER TABLE members ADD COLUMN IF NOT EXISTS height_cm NUMERIC(6,2);
    ALTER TABLE members ADD COLUMN IF NOT EXISTS weight_kg NUMERIC(6,2);
    ALTER TABLE members ADD COLUMN IF NOT EXISTS birth_date DATE;
    ALTER TABLE members ADD COLUMN IF NOT EXISTS neck_cm NUMERIC(6,2);
    ALTER TABLE members ADD COLUMN IF NOT EXISTS waist_cm NUMERIC(6,2);
    ALTER TABLE members ADD COLUMN IF NOT EXISTS hip_cm NUMERIC(6,2);
  `);

  /** Una sola membresía activa por socio (renovaciones anteriores quedan vencidas). */
  await pool.query(`
    UPDATE memberships ms
    SET status = 'expired'
    WHERE status = 'active'
      AND id <> (
        SELECT id
        FROM memberships
        WHERE member_id = ms.member_id AND status = 'active'
        ORDER BY start_date DESC, id DESC
        LIMIT 1
      )
  `);
}
